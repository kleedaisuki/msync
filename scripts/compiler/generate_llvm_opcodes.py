#!/usr/bin/env python3
"""Generate upstream LLVM instruction identities and the three project extensions."""
from __future__ import annotations

import json
from pathlib import Path
import re
from typing import Any

ROOT: Path = Path(__file__).resolve().parents[2]
REFERENCE: Path = ROOT / 'vendor/llvm-reference'
OUTPUT: Path = ROOT / 'src/Msync.Core/Llvm/LlvmOpcode.cs'


def generate() -> str:
    manifest: dict[str, Any] = json.loads((REFERENCE / 'SOURCE.json').read_text())
    source: Path = REFERENCE / 'llvm/include/llvm/IR/Instruction.def'
    entries: list[tuple[str, str]] = re.findall(
        r'^HANDLE_\w+_INST\s*\(\s*(\d+)\s*,\s*(\w+)\s*,', source.read_text(), re.MULTILINE,
    )
    header: str = (
        '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception\n'
        '// Generated by scripts/compiler/generate_llvm_opcodes.py; do not edit.\n'
        f'// LLVM source commit: {manifest["commit"]}\n'
        '// Source: llvm/include/llvm/IR/Instruction.def (license in vendor/llvm-reference/llvm/LICENSE.TXT).\n\n'
        'namespace Msync.Core.Llvm;\n\n'
        'public enum LlvmOpcode : byte\n{\n'
    )
    extensions: str = (
        '\n    // Project IR extensions, not upstream LLVM instructions.\n'
        '    HeapAlloc = 128,\n'
        '    FileIn = 129,\n'
        '    FileOut = 130,\n'
    )
    return header + ''.join(f'    {name} = {number},\n' for number, name in entries) + extensions + '}\n'


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generate())


if __name__ == '__main__':
    main()
