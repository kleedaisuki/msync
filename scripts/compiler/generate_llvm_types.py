#!/usr/bin/env python3
"""Generate LLVM TypeID identities from the inspected upstream Type.h."""
from __future__ import annotations

import json
from pathlib import Path
import re
from typing import Any

ROOT: Path = Path(__file__).resolve().parents[2]
REFERENCE: Path = ROOT / 'vendor/llvm-reference'
OUTPUT: Path = ROOT / 'src/Msync.Core/Llvm/LlvmTypeId.cs'


def generate() -> str:
    manifest: dict[str, Any] = json.loads((REFERENCE / 'SOURCE.json').read_text())
    source: str = (REFERENCE / 'llvm/include/llvm/IR/Type.h').read_text()
    body: str = source.split('enum TypeID {', 1)[1].split('};', 1)[0]
    members: list[str] = []
    value: int = 0
    for line in body.splitlines():
        match: re.Match[str] | None = re.match(r'\s*(\w+)\s*(?:=\s*(\d+))?\s*,', line)
        if match is None:
            continue
        if match[2] is not None:
            value = int(match[2])
        members.append(f'    {match[1]} = {value},\n')
        value += 1
    header: str = (
        '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception\n'
        '// Generated by scripts/compiler/generate_llvm_types.py; do not edit.\n'
        f'// LLVM source commit: {manifest["commit"]}\n'
        '// Source: llvm/include/llvm/IR/Type.h (license in vendor/llvm-reference/llvm/LICENSE.TXT).\n\n'
        'namespace Msync.Core.Llvm;\n\npublic enum LlvmTypeId : byte\n{\n'
    )
    return header + ''.join(members) + '}\n'


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generate())


if __name__ == '__main__':
    main()
