#!/usr/bin/env python3
"""Translate Value.h's two Value.def enum expansions without adding value kinds."""
from __future__ import annotations

import json
from pathlib import Path
import re
from typing import Any

ROOT: Path = Path(__file__).resolve().parents[2]
REFERENCE: Path = ROOT / 'vendor/llvm-reference'
OUTPUT: Path = ROOT / 'src/Msync.Core/Llvm/LlvmValueKind.cs'


def generate() -> str:
    manifest: dict[str, Any] = json.loads((REFERENCE / 'SOURCE.json').read_text())
    source: str = (REFERENCE / 'llvm/include/llvm/IR/Value.def').read_text()
    values: list[str] = re.findall(r'^HANDLE_(?!CONSTANT_MARKER)\w+\((\w+)\)', source, re.MULTILINE)
    markers: list[tuple[str,str]] = re.findall(r'^HANDLE_CONSTANT_MARKER\((\w+),\s*(\w+)\)',source,re.MULTILINE)
    header: str = (
        '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception\n'
        '// Generated by scripts/compiler/generate_llvm_values.py; do not edit.\n'
        f'// LLVM source commit: {manifest["commit"]}\n'
        '// Source: Value.h ValueTy / Value.def (license in vendor/llvm-reference/llvm/LICENSE.TXT).\n\n'
        'namespace Msync.Core.Llvm;\n\npublic enum LlvmValueKind : byte\n{\n'
    )
    members: str = ''.join(f'    {name}Val = {number},\n' for number,name in enumerate(values))
    aliases: str = ''.join(f'    {marker} = {name}Val,\n' for marker,name in markers)
    return header + members + aliases + '}\n'


def main() -> None:
    OUTPUT.parent.mkdir(parents=True,exist_ok=True)
    OUTPUT.write_text(generate())


if __name__ == '__main__':
    main()
