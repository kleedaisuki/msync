#!/usr/bin/env python3
"""Generate Native AOT casing tables from the pinned Unicode Character Database."""

from __future__ import annotations

import argparse
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "vendor/unicode/17.0.0"
OUTPUT = ROOT / "src/Msync.Runtime/Generated/UnicodeCasingData.cs"
Mapping = dict[int, tuple[int, ...]]
Interval = tuple[int, int]


@dataclass(frozen=True)
class Tables:
    lower: Mapping
    upper: Mapping
    cased: list[Interval]
    ignorable: list[Interval]


def mappings() -> tuple[Mapping, Mapping]:
    lower: Mapping = {}
    upper: Mapping = {}
    for line in (SOURCE / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        scalar = int(fields[0], 16)
        if fields[13]:
            lower[scalar] = (int(fields[13], 16),)
        if fields[12]:
            upper[scalar] = (int(fields[12], 16),)
    for line in (SOURCE / "SpecialCasing.txt").read_text(encoding="utf-8").splitlines():
        content = line.split("#", 1)[0].strip()
        if not content:
            continue
        fields = [field.strip() for field in content.split(";")]
        if fields[4]:
            continue
        scalar = int(fields[0], 16)
        lower[scalar] = tuple(int(value, 16) for value in fields[1].split())
        upper[scalar] = tuple(int(value, 16) for value in fields[3].split())
    return (
        {key: value for key, value in lower.items() if value != (key,)},
        {key: value for key, value in upper.items() if value != (key,)},
    )


def properties() -> tuple[list[Interval], list[Interval]]:
    found: dict[str, list[Interval]] = {"Cased": [], "Case_Ignorable": []}
    text = (SOURCE / "DerivedCoreProperties.txt").read_text(encoding="utf-8")
    for line in text.splitlines():
        content = line.split("#", 1)[0].strip()
        if not content:
            continue
        fields = [field.strip() for field in content.split(";")]
        if fields[1] not in found:
            continue
        bounds = [int(value, 16) for value in fields[0].split("..")]
        found[fields[1]].append((bounds[0], bounds[-1]))
    return merged(found["Cased"]), merged(found["Case_Ignorable"])


def merged(intervals: list[Interval]) -> list[Interval]:
    result: list[Interval] = []
    for start, end in sorted(intervals):
        if result and start <= result[-1][1] + 1:
            result[-1] = (result[-1][0], max(end, result[-1][1]))
        else:
            result.append((start, end))
    return result


def integer_span(name: str, values: Iterable[int]) -> str:
    items = [f"0x{value:X}" for value in values]
    lines = [", ".join(items[index : index + 12]) for index in range(0, len(items), 12)]
    body = "\n".join(f"        {line}," for line in lines)
    return f"    internal static ReadOnlySpan<int> {name} =>\n    [\n{body}\n    ];\n"


def mapping_table(name: str, mapping: Mapping) -> str:
    entries: list[int] = []
    units: list[int] = []
    for scalar, mapped in sorted(mapping.items()):
        encoded = "".join(chr(value) for value in mapped).encode("utf-16-le")
        encoded_units = [
            int.from_bytes(encoded[index : index + 2], "little")
            for index in range(0, len(encoded), 2)
        ]
        entries.extend((scalar, len(units), len(encoded_units)))
        units.extend(encoded_units)
    chunks = [
        "".join(f"\\u{unit:04X}" for unit in units[index : index + 24])
        for index in range(0, len(units), 24)
    ]
    text = " +\n".join(f'        "{chunk}"' for chunk in chunks)
    return (
        integer_span(f"{name}Mappings", entries)
        + f"\n    internal const string {name}Text =\n{text};\n"
    )


def generate(tables: Tables) -> str:
    pieces = [
        (
            "// Generated by scripts/generate_unicode.py from Unicode 17.0.0.\n"
            "// SPDX-License-Identifier: Unicode-3.0\n"
            "// See vendor/unicode/LICENSE.txt for the Unicode data license.\n"
            "namespace Msync.Runtime;\n\n"
            "internal static class UnicodeCasingData\n{\n"
        ),
        mapping_table("Lower", tables.lower),
        mapping_table("Upper", tables.upper),
        integer_span("Cased", (value for pair in tables.cased for value in pair)),
        integer_span(
            "CaseIgnorable", (value for pair in tables.ignorable for value in pair)
        ),
        "}\n",
    ]
    return "\n".join(pieces)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lower, upper = mappings()
    cased, ignorable = properties()
    generated = generate(Tables(lower, upper, cased, ignorable))
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit(
                f"{OUTPUT.relative_to(ROOT)} differs from pinned Unicode data"
            )
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
    print(
        f"Unicode 17: {len(lower)} lower, {len(upper)} upper mappings; {len(cased)} cased and {len(ignorable)} ignorable ranges"
    )


if __name__ == "__main__":
    main()
