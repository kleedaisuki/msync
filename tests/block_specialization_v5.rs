use msync::endpoint::{Backend, Location};
use msync::hir::graph::PlanningContext;
use msync::hir::{
    BarrierKind, Input, Instruction, InstructionId, InstructionKind, Output, Program, Region,
};
use msync::language::DestinationMode;
use msync::preparation;
use msync::syntax::Span;

fn workspace() -> tempfile::TempDir {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(".temp");
    std::fs::create_dir_all(&root).unwrap();
    tempfile::tempdir_in(root).unwrap()
}
fn transfer(id: usize, source: Input, destination: &std::path::Path) -> Instruction {
    Instruction {
        id: InstructionId(id),
        kind: InstructionKind::Transfer {
            source,
            destination: Output::File {
                location: Location {
                    backend: Backend::Local,
                    path: destination.to_string_lossy().into_owned(),
                },
                mode: DestinationMode::Exact,
            },
        },
        span: Span::default(),
        expansion: Vec::new(),
    }
}

fn file(path: &std::path::Path) -> Input {
    Input::File {
        location: Location {
            backend: Backend::Local,
            path: path.to_string_lossy().into_owned(),
        },
        pattern: None,
    }
}

#[test]
fn whole_module_inspection_rejects_before_touching_future_missing_source() {
    let root = workspace();
    let program = Program {
        body: Region {
            instructions: vec![
                transfer(
                    0,
                    Input::Literal("first".into()),
                    &root.path().join("first"),
                ),
                Instruction {
                    id: InstructionId(1),
                    kind: InstructionKind::Barrier {
                        kind: BarrierKind::After,
                    },
                    span: Span::default(),
                    expansion: Vec::new(),
                },
                transfer(
                    2,
                    file(&root.path().join("future-missing")),
                    &root.path().join("last"),
                ),
            ],
        },
    };
    let errors = preparation::prepare(&program, true).unwrap_err();
    assert_eq!(errors.len(), 1);
    assert!(errors[0].diagnostic.message.contains("one basic block"));
    assert!(!root.path().join("first").exists());
}

#[test]
fn dispatch_resolves_new_file_and_rejects_later_external_deletion() {
    let root = workspace();
    let generated = root.path().join("generated");
    let op = transfer(0, file(&generated), &root.path().join("result"));
    assert!(preparation::resolve_instruction(&op, &PlanningContext::default()).is_err());
    std::fs::write(&generated, b"generated by external program").unwrap();
    let (_, context) = preparation::resolve_instruction(&op, &PlanningContext::default()).unwrap();
    assert_eq!(
        context.operation_facts[&op.id].source,
        msync::plan::FileClass::Regular
    );
    std::fs::remove_file(generated).unwrap();
    assert!(preparation::resolve_instruction(&op, &PlanningContext::default()).is_err());
    assert!(preparation::resolve_instruction(&op, &context).is_err());
}

#[test]
fn within_block_producer_supplies_missing_source_postcondition() {
    let root = workspace();
    let middle = root.path().join("middle");
    let program = Program {
        body: Region {
            instructions: vec![
                transfer(0, Input::Literal("payload".into()), &middle),
                transfer(1, file(&middle), &root.path().join("out")),
            ],
        },
    };
    let block = program.blocks().next().unwrap();
    let prepared = preparation::prepare_block(&block, PlanningContext::default()).unwrap();
    assert_eq!(
        prepared.facts[&InstructionId(1)].source,
        msync::plan::FileClass::Regular
    );
    assert!(
        !middle.exists(),
        "preparation must not execute the producer"
    );
}

#[cfg(windows)]
#[tokio::test]
async fn preparing_named_pipe_source_and_destination_never_connects_to_waiting_servers() {
    use std::time::Duration;
    use tokio::net::windows::named_pipe::{ClientOptions, ServerOptions};

    let root = workspace();
    let pipe = format!(
        r"\\.\pipe\msync-prepare-no-client-{}-{}",
        std::process::id(),
        root.path().file_name().unwrap().to_string_lossy()
    );
    let first = ServerOptions::new()
        .first_pipe_instance(true)
        .max_instances(2)
        .create(&pipe)
        .unwrap();
    let second = ServerOptions::new().max_instances(2).create(&pipe).unwrap();
    let source = transfer(
        0,
        file(std::path::Path::new(&pipe)),
        &root.path().join("output"),
    );
    let destination = transfer(
        1,
        Input::Literal("not sent".into()),
        std::path::Path::new(&pipe),
    );
    for node in [source, destination] {
        let program = Program {
            body: Region {
                instructions: vec![node],
            },
        };
        let prepared = preparation::prepare(&program, true).unwrap();
        assert!(prepared.rewrites.is_empty());
        prepared.verify().unwrap();
    }
    assert!(
        tokio::time::timeout(Duration::from_millis(50), first.connect())
            .await
            .is_err(),
        "preparation consumed the first pipe connection"
    );
    assert!(
        tokio::time::timeout(Duration::from_millis(50), second.connect())
            .await
            .is_err(),
        "preparation consumed the second pipe connection"
    );
    let first_client = ClientOptions::new().open(&pipe).unwrap();
    tokio::time::timeout(Duration::from_secs(2), first.connect())
        .await
        .unwrap()
        .unwrap();
    let second_client = ClientOptions::new().open(&pipe).unwrap();
    tokio::time::timeout(Duration::from_secs(2), second.connect())
        .await
        .unwrap()
        .unwrap();
    drop((first_client, second_client));
    assert!(!root.path().join("output").exists());
}

#[test]
fn known_process_ids_do_not_hide_fresh_parent_frontiers_or_file_kinds() {
    let root = workspace();
    let source = root.path().join("source");
    std::fs::write(&source, b"actual current bytes").unwrap();
    let program = Program {
        body: Region {
            instructions: vec![
                transfer(0, file(&source), &root.path().join("left")),
                transfer(
                    1,
                    Input::Literal("right".into()),
                    &root.path().join("right"),
                ),
            ],
        },
    };
    let context = PlanningContext {
        live_processes: vec![msync::hir::ProcessId(0), msync::hir::ProcessId(900)],
        ..PlanningContext::default()
    };
    let prepared = preparation::prepare_with_context(&program, true, context).unwrap();
    assert_eq!(
        prepared.facts[&InstructionId(0)].source,
        msync::plan::FileClass::Regular
    );
    assert_eq!(prepared.context.existing_parent_frontiers.len(), 2);
    assert!(prepared.graph.dependencies.is_empty());
    prepared.verify().unwrap();
}

#[test]
#[ignore = "child fixture invoked by running_and_exited_process_ids_keep_current_block_observations_fresh"]
fn runtime_fact_child() {
    let Some(directory) = std::env::var_os("MSYNC_PREPARATION_FACT_CHILD") else {
        return;
    };
    let directory = std::path::PathBuf::from(directory);
    std::fs::write(directory.join("ready"), b"ready").unwrap();
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(15);
    while !directory.join("release").exists() && std::time::Instant::now() < deadline {
        std::thread::sleep(std::time::Duration::from_millis(5));
    }
}

#[test]
fn running_and_exited_process_ids_keep_current_block_observations_fresh() {
    let root = workspace();
    let source = root.path().join("source");
    std::fs::write(&source, b"first observed value").unwrap();
    let operation = transfer(0, file(&source), &root.path().join("result"));
    let mut child = std::process::Command::new(std::env::current_exe().unwrap())
        .args([
            "--exact",
            "runtime_fact_child",
            "--ignored",
            "--test-threads=1",
        ])
        .env("MSYNC_PREPARATION_FACT_CHILD", root.path())
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn()
        .unwrap();
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(5);
    while !root.path().join("ready").exists() && std::time::Instant::now() < deadline {
        std::thread::sleep(std::time::Duration::from_millis(5));
    }
    assert!(root.path().join("ready").exists());
    assert!(child.try_wait().unwrap().is_none());
    let context = PlanningContext {
        live_processes: vec![msync::hir::ProcessId(child.id() as usize)],
        ..PlanningContext::default()
    };
    let running = preparation::resolve_instruction(&operation, &context);
    std::fs::write(root.path().join("release"), b"finish naturally").unwrap();
    assert!(child.wait().unwrap().success());
    let (_, running_context) = running.unwrap();
    assert_eq!(
        running_context.operation_facts[&operation.id].source,
        msync::plan::FileClass::Regular
    );
    assert_eq!(running_context.existing_parent_frontiers.len(), 1);
    let (_, exited_context) =
        preparation::resolve_instruction(&operation, &running_context).unwrap();
    assert_eq!(
        exited_context.operation_facts[&operation.id].source,
        msync::plan::FileClass::Regular
    );
    std::fs::remove_file(source).unwrap();
    assert!(preparation::resolve_instruction(&operation, &exited_context).is_err());
}
